#!/usr/bin/env bash
# OpenChoreo IDP (OKE lab) clients in Authentik. The OpenChoreo API validates one
# issuer (global iss) and does not validate the audience. All OpenChoreo providers
# share the "authentik Self-signed Certificate" with the other applications, so the
# only barrier against a token of another application is `iss`:
#   - `issuer_mode: global` is reserved to the OpenChoreo providers;
#   - one provider per client, distinct client_id;
#   - service clients: client_credentials only, fixed `client_id` claim, no human binding;
#   - human clients: filtered `groups` claim, bound to OpenChoreo groups or admins only;
#   - no client secret in Git (Authentik generates it).
set -euo pipefail
auth=k8s/infrastructure/auth/authentik/extra
bp="$auth/blueprints"
files=(apps-openchoreo.yaml apps-openchoreo-agents.yaml)
fail() { echo "AUTHENTIK_OPENCHOREO=FAIL $*" >&2; exit 1; }

for f in "${files[@]}" apps-miniflux-lab.yaml; do
  [ -f "$bp/$f" ] || fail "$f missing"
  grep -Eq "^[[:space:]]*-[[:space:]]*\./blueprints/${f//./\\.}" "$auth/kustomization.yml" \
    || fail "$f is not in the authentik-blueprints ConfigMap"
  if grep -Eq '^[[:space:]]*-?[[:space:]]*(client_secret|password|token|key_data|certificate_data)[[:space:]]*:' "$bp/$f"; then
    fail "secret attribute in $f"
  fi
  if grep -v '^[[:space:]]*#' "$bp/$f" | grep -q '!Env'; then
    fail "$f must not read environment values"
  fi
done

python3 - "$bp" "${files[@]}" <<'PY'
import os, re, sys, yaml

class Loader(yaml.SafeLoader):
    pass

def tag(loader, suffix, node):
    if isinstance(node, yaml.SequenceNode):
        return ["!" + suffix, loader.construct_sequence(node, deep=True)]
    if isinstance(node, yaml.MappingNode):
        return ["!" + suffix, loader.construct_mapping(node, deep=True)]
    return ["!" + suffix, loader.construct_scalar(node)]

Loader.add_multi_constructor("!", tag)
bp_dir, oc_files = sys.argv[1], set(sys.argv[2:])
KEY = "authentik Self-signed Certificate"
HUMAN = {"openchoreo-backstage-client", "openchoreo-cli"}
SERVICE = {"openchoreo-backstage-service", "openchoreo-agent-reader", "openchoreo-agent-operator"}
GROUPS = {"authentik-admins", "openchoreo-developers", "openchoreo-viewers"}

def find_name(ref):
    # !Find [model, [field, "value"]] -> value
    if isinstance(ref, list) and ref and ref[0] == "!Find":
        return ref[1][1][1]
    return None

client_ids = {}
oc = {}  # client_id -> (file, entry, ids)
for name in sorted(os.listdir(bp_dir)):
    if not name.endswith(".yaml"):
        continue
    doc = yaml.load(open(os.path.join(bp_dir, name)), Loader=Loader) or {}
    entries = doc.get("entries") or []
    ids = {e["id"]: e for e in entries if "id" in e}
    for e in entries:
        if e.get("model") != "authentik_providers_oauth2.oauth2provider" or e.get("state") == "absent":
            continue
        a = e.get("attrs") or {}
        cid = a.get("client_id")
        if isinstance(cid, str):
            assert cid not in client_ids, f"client_id {cid} in {name} and {client_ids[cid]}"
            client_ids[cid] = name
        if a.get("issuer_mode") == "global":
            assert name in oc_files and cid in HUMAN | SERVICE, \
                f"{name}: issuer_mode global is reserved to the OpenChoreo providers ({cid!r})"
        if name in oc_files:
            oc[cid] = (name, e, ids, entries)

assert set(oc) == HUMAN | SERVICE, f"OpenChoreo providers {sorted(oc)} != {sorted(HUMAN | SERVICE)}"

for cid, (name, e, ids, entries) in oc.items():
    a = e["attrs"]
    assert a.get("issuer_mode") == "global", f"{cid}: issuer_mode must be global (one issuer)"
    assert find_name(a.get("signing_key")) == KEY, f"{cid}: signing_key must be {KEY!r} (one JWKS)"
    assert "client_secret" not in a, f"{cid}: client_secret is generated by Authentik"
    maps = a.get("property_mappings") or []
    scopes = [find_name(m) for m in maps if find_name(m)]
    assert "groups" not in scopes, f"{cid}: unfiltered groups mapping forbidden"
    local = [ids[m[1]] for m in maps if isinstance(m, list) and m[0] == "!KeyOf"]
    app = [x for x in entries if x.get("model") == "authentik_core.application"
           and x["attrs"].get("provider") == ["!KeyOf", e["id"]]]
    assert len(app) == 1, f"{cid}: exactly one application"
    app_id = app[0]["id"]
    bound = [x for x in entries if x.get("model") == "authentik_policies.policybinding"
             and x["identifiers"].get("target") == ["!KeyOf", app_id]]
    if cid in SERVICE:
        assert a["grant_types"] == ["client_credentials"], f"{cid}: client_credentials only"
        assert not a.get("redirect_uris"), f"{cid}: no redirect URI"
        assert a.get("client_type") == "confidential", f"{cid}: confidential"
        assert len(local) == 1 and local[0]["attrs"]["scope_name"] == "openchoreo-client-id", \
            f"{cid}: one openchoreo-client-id mapping"
        expr = local[0]["attrs"]["expression"].strip()
        assert expr == 'return {"client_id": "%s"}' % cid, f"{cid}: client_id claim must be fixed to {cid}"
        assert not bound, f"{cid}: no policy binding on a machine identity"
    else:
        assert "authorization_code" in a["grant_types"], f"{cid}: authorization_code"
        assert "client_credentials" not in a["grant_types"], f"{cid}: no client_credentials"
        assert len(local) == 1 and local[0]["attrs"]["scope_name"] == "openchoreo", \
            f"{cid}: one openchoreo claims mapping"
        allowed = set(re.findall(r'"([a-z-]+)"', local[0]["attrs"]["expression"].split("\n")[0]))
        assert allowed == GROUPS, f"{cid}: claims mapping groups {sorted(allowed)} != {sorted(GROUPS)}"
        groups = set()
        for b in bound:
            g = b["identifiers"].get("group")
            groups.add(find_name(g) or ids[g[1]]["attrs"]["name"])
        assert groups == GROUPS, f"{cid}: bound groups {sorted(groups)} != {sorted(GROUPS)}"
PY

echo 'AUTHENTIK_OPENCHOREO=PASS STATIC; NO CLIENT EXISTS IN AUTHENTIK YET'
